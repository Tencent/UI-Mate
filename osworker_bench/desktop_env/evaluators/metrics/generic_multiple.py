def _extract_single_slide_pptx(src_pptx, slide_idx_0based, dst_pptx):
    """Write a new pptx that contains ONLY the ``slide_idx_0based``-th slide
    of ``src_pptx``.

    Implementation: copy the source file via ``pptx.Presentation``, then
    drop every other slide from ``prs.slides._sldIdLst`` using python-pptx's
    official recipe for removing slides. The removed slides' parts remain
    in the package (orphaned), but ``prs.slides`` iteration will now only
    yield the requested slide, which is all ``compare_pptx_files`` needs.

    If ``slide_idx_0based`` is out of range (e.g. agent produced fewer
    slides than expected), the destination pptx is written with zero
    slides; subsequent compare_pptx_files call will naturally fail to
    match because slide counts differ.
    """
    from pptx import Presentation  # local import to avoid hard dep

    prs = Presentation(src_pptx)
    xml_slides = prs.slides._sldIdLst
    slides_list = list(xml_slides)

    for i, sld_id_elem in enumerate(slides_list):
        if i != slide_idx_0based:
            xml_slides.remove(sld_id_elem)

    prs.save(dst_pptx)


