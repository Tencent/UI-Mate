def evaluate_generic_multiple(result, expected=None, **options):
    """
    Generic multi-file wrapper for standard two-file comparison functions.
    Dispatches to options["original_func"](result[i], expected[i], **options).
    Score = matched_count / total_count.
    """
    original_func_name = options.pop("original_func", None)
    if not original_func_name:
        print("[Eval Error] options['original_func'] is missing")
        return 0.0

    func = getattr(_metrics, original_func_name, None)
    if func is None:
        print(f"[Eval Error] Function '{original_func_name}' not found in metrics")
        return 0.0

