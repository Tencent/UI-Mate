def _slice_single_row_xlsx(src_xlsx, row_idx_1based, header_rows, dst_xlsx):
    """Write a new xlsx containing header + the N-th data row of ``src_xlsx``.

    ``row_idx_1based`` is the 1-based index of the data row (1 == first
    data row, counted AFTER the header). If the requested data row does
    not exist (agent produced fewer rows than expected), the destination
    xlsx still contains the header and is left data-row-less, so the
    per-row comparison will score 0 naturally.
    """
    wb_src = openpyxl.load_workbook(src_xlsx, data_only=True)
    wb_dst = openpyxl.Workbook()
    # Drop default empty sheet; mirror source sheet order/names.
    wb_dst.remove(wb_dst.active)
    for ws_src in wb_src.worksheets:
        ws_dst = wb_dst.create_sheet(title=ws_src.title)
        # 1) copy header rows verbatim
        for r in range(1, header_rows + 1):
            if r > ws_src.max_row:
                break
            for c_idx, cell in enumerate(ws_src[r], start=1):
                ws_dst.cell(row=r, column=c_idx, value=cell.value)
        # 2) copy the requested data row into (header_rows + 1)
        abs_row = header_rows + row_idx_1based
        if 1 <= abs_row <= ws_src.max_row:
            for c_idx, cell in enumerate(ws_src[abs_row], start=1):
                ws_dst.cell(row=header_rows + 1, column=c_idx, value=cell.value)
    wb_dst.save(dst_xlsx)


def compare_table_partial_rows(result, expected=None, **options):
    """
    Row-level partial-scoring wrapper for ``compare_table`` (and other
    two-file table comparators sharing the same signature).

    For each data row i = 1..N (N = number of data rows in ``expected``),
    slices ``result`` and ``expected`` into temporary [header + row i]
    single-row xlsx files and re-runs the original comparator. The final
    score is matched_rows / N.

    Usage in JSON evaluator config:

        {
          "func": "compare_table_partial_rows",
          "result":   { "type": "vm_file",    ... },
          "expected": { "type": "cloud_file", ... },
          "options": {
            "original_func":   "compare_table",
            "sub_rule":        {"type": "sheet_data",
                                 "sheet_idx0": "RI0", "sheet_idx1": "EI0"},
            "header_rows":     1,
            "match_strategy":  "ordered",
            "total_rows":      5
          }
        }

    Recognised options:
      - original_func  (str, default "compare_table")
      - sub_rule       (dict, required)  a single rule for the comparator.
                        Wrapper will invoke ``func(r, e, rules=[sub_rule])``.
      - header_rows    (int, default 1)
      - match_strategy ("ordered" | "unordered", default "ordered").
                        "unordered" is reserved and not yet implemented.
      - total_rows     (int, optional)  override the number of expected rows.
                        Defaults to ``max_row - header_rows`` of the expected
                        file.

    Design choice: we do NOT re-implement pandas equality; we delegate
    each row comparison to the ORIGINAL ``compare_table`` so behaviour is
    identical (precision rounding, sheet idx parsing, NaN handling, ...).
    """
    # Avoid mutating caller's dict
    options = dict(options) if options else {}

    original_func_name = options.pop("original_func", "compare_table")
    func = getattr(_metrics, original_func_name, None)
    if func is None:
        print(f"[Eval Error] Function '{original_func_name}' not found in metrics")
        return 0.0

    sub_rule = options.pop("sub_rule", None)
    if sub_rule is None:
        print("[Eval Error] options['sub_rule'] is required for compare_table_partial_rows")
        return 0.0

    header_rows = options.pop("header_rows", 1)
    match_strategy = options.pop("match_strategy", "ordered")
    total_rows_hint = options.pop("total_rows", None)

    if not (isinstance(result, str) and isinstance(expected, str)):
        print(
            f"[Eval Error] compare_table_partial_rows expects result/expected as str file paths, "
            f"got result={type(result).__name__}, expected={type(expected).__name__}"
        )
        return 0.0
    if not os.path.exists(result):
        print(f"[Eval Error] result file not found: {result}")
        return 0.0
    if not os.path.exists(expected):
        print(f"[Eval Error] expected file not found: {expected}")
        return 0.0

    # 1) Determine total number of data rows in expected (first sheet).
    try:
        wb_exp = openpyxl.load_workbook(expected, data_only=True)
        ws_exp = wb_exp.worksheets[0]
        total_data_rows = max(0, ws_exp.max_row - header_rows)
    except Exception as e:
        print(f"[Eval Error] Failed to open expected xlsx: {e}")
        return 0.0

    total = total_rows_hint if total_rows_hint is not None else total_data_rows
    if total <= 0:
        print("[Eval Warning] No data rows in expected; score=0.0")
        return 0.0

    # 2) Per-row comparison. Keep the wrapper pass-through: forward any
    #    remaining options (besides our own meta-keys) to the sub-call
    #    together with rules=[sub_rule].
    sub_call_options = dict(options)
    sub_call_options["rules"] = [sub_rule]

    if match_strategy != "ordered":
        raise NotImplementedError(
            f"compare_table_partial_rows: match_strategy='{match_strategy}' "
            f"not implemented yet (only 'ordered' supported)"
        )

    matched = 0
    with tempfile.TemporaryDirectory() as tmpd:
        for i in range(1, total + 1):
            r_tmp = os.path.join(tmpd, f"result_row{i}.xlsx")
            e_tmp = os.path.join(tmpd, f"expected_row{i}.xlsx")
            try:
                _slice_single_row_xlsx(result, i, header_rows, r_tmp)
                _slice_single_row_xlsx(expected, i, header_rows, e_tmp)
                score = func(r_tmp, e_tmp, **sub_call_options)
                if score >= 0.99:
                    matched += 1
                    print(f"[Eval Info] Row {i}/{total} matched")
                else:
                    print(f"[Eval Info] Row {i}/{total} NOT matched (score={score:.4f})")
            except Exception as e:
                print(f"[Eval Error] Row {i}/{total}: {e}")

    final_score = matched / total if total > 0 else 0.0
    print(f"[Eval Result] {matched}/{total} rows matched. Score: {final_score:.4f}")
    return final_score




