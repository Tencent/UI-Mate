def evaluate_generic_mixed_and_multiple(result, expected=None, **options):
    """
    Generic multi-file combined-and wrapper.
    For each file, runs ALL sub-functions (and-logic).
    A file passes only if all sub-functions pass. Score = passed / N.

    options["sub_funcs_config"] is a list of dicts, one per sub-function:
      {"func": "funcA", "expected_type": "rule"|"cloud_file",
        "rules": {...},   # only if expected_type == "rule"
        "options": {...}   # sub-function specific options
      }
    """
    # 1. Normalize result to list
    if isinstance(result, str):
        result_files = [result]
    elif isinstance(result, list):
        result_files = result
    else:
        print(f"[Eval Warning] 'result' is not list or str, got {type(result)}")
        return 0.0

    N = len(result_files)
    if N == 0:
        return 0.0

    # 2. Normalize expected (gold files) to list
    if expected is None:
        expected_files = [None] * N
    elif isinstance(expected, str):
        expected_files = [expected]
    elif isinstance(expected, list):
        expected_files = expected
    else:
        expected_files = [None] * N

    sub_funcs_config = options.get("sub_funcs_config", [])

    # 3. For each result file, run all sub-functions
    matched_count = 0

    for i in range(N):
        all_passed = True
        gold_offset = i  # Offset into the gold file sequence

        for sc in sub_funcs_config:
            fname = sc["func"]
            exp_type = sc.get("expected_type", "unknown")
            sub_opts = sc.get("options", {})

            func = getattr(_metrics, fname, None)
            if func is None:
                print(f"[Eval Error] Function '{fname}' not found in metrics")
                all_passed = False
                break

            try:
                if exp_type == "cloud_file":
                    g_idx = gold_offset
                    gold_file = expected_files[g_idx] if g_idx < len(expected_files) else None
                    gold_offset += N

                    if sub_opts:
                        try:
                            score = func(result_files[i], gold_file, **sub_opts)
                        except TypeError:
                            score = func(result_files[i], gold_file)
                    else:
                        score = func(result_files[i], gold_file)

                elif exp_type == "rule":
                    rules = sc.get("rules", {})
                    score = func(result_files[i], rules)
                else:
                    print(f"[Eval Warning] Unknown expected_type '{exp_type}' for {fname}")
                    score = 0.0

                if score < 0.99:
                    print(f"[Eval Info] File {i+1}/{N} failed {fname} (score={score:.4f})")
                    all_passed = False
                    break
                else:
                    print(f"[Eval Info] File {i+1}/{N} passed {fname} (score={score:.4f})")

            except Exception as e:
                print(f"[Eval Error] File {i+1}/{N} {fname} error: {e}")
                all_passed = False
                break

        if all_passed:
            matched_count += 1
            print(f"[Eval Success] File {i+1}/{N} passed ALL checks")
        else:
            print(f"[Eval Info] File {i+1}/{N} FAILED combined check")

    final_score = matched_count / N if N > 0 else 0.0
    print(f"[Eval Result] {matched_count}/{N} files passed all checks. Score: {final_score:.4f}")
    return final_score





def evaluate_rule_check_partial_scoring(result, expected=None, **options):
    """
    Partial-scoring wrapper for rule-check evaluators (e.g. check_thunderbird_filter).

    Unlike the original function which returns all-or-nothing (1.0 only if ALL
    rules match), this wrapper calls the original function once per rule in the
    ``expect`` list, giving partial credit: score = matched_rules / total_rules.

    This is designed for the scenario where:
      - There is only 1 result file (e.g. msgFilterRules.dat) containing N rules
      - The original evaluator signature is: func(result_path, rules_dict) -> float
      - rules_dict has the shape: {"expect": [...], "unexpect": [...]}

    Usage in JSON evaluator config:
      {
        "func": "evaluate_rule_check_partial_scoring",
        "result": { ... },          // same as original (e.g. vm_file)
        "expected": {
          "type": "rule",
          "rules": {
            "expect": [ rule1, rule2, ... ruleN ],
            "unexpect": [ ... ]     // optional, checked once globally
          }
        },
        "options": {
          "original_func": "check_thunderbird_filter"
        }
      }

    Scoring logic:
      1. For each rule in expect[], call original_func with a single-rule subset
         → count how many individual rules pass
      2. If unexpect[] exists, call original_func once with all unexpect rules
         → if any unexpect rule matches, score = 0.0
      3. Final score = matched_expect_count / total_expect_count
    """
    original_func_name = options.pop("original_func", None)
    if not original_func_name:
        print("[Eval Error] options['original_func'] is missing")
        return 0.0

    func = getattr(_metrics, original_func_name, None)
    if func is None:
        print(f"[Eval Error] Function '{original_func_name}' not found in metrics")
        return 0.0

    if result is None:
        print("[Eval Error] result is None")
        return 0.0

    # 1. Extract rules from expected
    # get_rule getter returns config["rules"], which is {"expect": [...], "unexpect": [...]}
    # So expected may be:
    #   a) {"expect": [...], "unexpect": [...]}  — from get_rule getter (most common)
    #   b) {"rules": {"expect": [...], ...}}     — if passed with extra nesting
    #   c) {"type": "rule", "rules": {...}}      — if passed raw from JSON
    rules = None
    if isinstance(expected, dict):
        if "expect" in expected or "unexpect" in expected:
            # Case (a): expected IS the rules dict directly
            rules = expected
        elif "rules" in expected:
            # Case (b) or (c): expected has a "rules" sub-dict
            rules = expected["rules"]

    if rules is None:
        # Fallback: call original function directly (all-or-nothing)
        print("[Eval Warning] No 'expect'/'rules' found in expected, falling back to original func")
        try:
            return func(result, expected, **options) if options else func(result, expected)
        except Exception as e:
            print(f"[Eval Error] Fallback call failed: {e}")
            return 0.0

    expect_rules = rules.get("expect", [])
    unexpect_rules = rules.get("unexpect", [])
    total_count = len(expect_rules)

    if total_count == 0:
        print("[Eval Warning] No expect rules found")
        return 0.0

    # 2. Check unexpect rules first (global check, must all pass)
    if unexpect_rules:
        try:
            unexpect_check_rules = {"expect": [], "unexpect": unexpect_rules}
            unexpect_score = func(result, unexpect_check_rules)
            if unexpect_score < 0.99:
                print(f"[Eval Info] Unexpect rules check FAILED — unwanted filters found")
                return 0.0
            else:
                print(f"[Eval Info] Unexpect rules check passed")
        except Exception as e:
            print(f"[Eval Error] Unexpect rules check error: {e}")
            return 0.0

    # 3. Check rules — either by round_groups or individually
    round_groups = options.pop("round_groups", None)

    if round_groups:
        # --- Round-based scoring: each round is a group of rule indices ---
        # All rules in a round must match for the round to count.
        # Score = completed_rounds / total_rounds
        num_rounds = len(round_groups)
        completed_rounds = 0

        for r_idx, group_indices in enumerate(round_groups):
            round_rules = [expect_rules[j] for j in group_indices if j < total_count]
            if not round_rules:
                print(f"[Eval Warning] Round {r_idx+1}/{num_rounds} has no valid rules, skipping")
                continue

            round_passed = True
            for rule in round_rules:
                try:
                    single_rule_set = {"expect": [rule]}
                    score = func(result, single_rule_set)
                    if score < 0.99:
                        round_passed = False
                        print(f"[Eval Info] Round {r_idx+1}/{num_rounds} rule NOT matched: {rule}")
                        break
                    else:
                        print(f"[Eval Info] Round {r_idx+1}/{num_rounds} rule matched: {rule}")
                except Exception as e:
                    print(f"[Eval Error] Round {r_idx+1}/{num_rounds} rule error: {e}")
                    round_passed = False
                    break

            if round_passed:
                completed_rounds += 1
                print(f"[Eval Info] Round {r_idx+1}/{num_rounds} COMPLETED ✓")
            else:
                print(f"[Eval Info] Round {r_idx+1}/{num_rounds} INCOMPLETE ✗")

        final_score = completed_rounds / num_rounds if num_rounds > 0 else 0.0
        print(f"[Eval Result] {completed_rounds}/{num_rounds} rounds completed. Score: {final_score:.4f}")
        return final_score

    else:
        # --- Per-rule scoring (original behavior) ---
        matched_count = 0
        for i, rule in enumerate(expect_rules):
            try:
                single_rule_set = {"expect": [rule]}
                score = func(result, single_rule_set)
                if score >= 0.99:
                    matched_count += 1
                    print(f"[Eval Info] Rule {i+1}/{total_count} matched: {rule}")
                else:
                    print(f"[Eval Info] Rule {i+1}/{total_count} NOT matched: {rule}")
            except Exception as e:
                print(f"[Eval Error] Rule {i+1}/{total_count} error: {e}")

        final_score = matched_count / total_count if total_count > 0 else 0.0
        print(f"[Eval Result] {matched_count}/{total_count} rules matched. Score: {final_score:.4f}")
        return final_score






